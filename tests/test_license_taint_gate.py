REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
BASELINE_DIR = REPO_ROOT / "data" / "baselines" / "ets2_1.62_def"
LAWS_DIR = REPO_ROOT / "data" / "laws"
MAPPINGS_PATH = REPO_ROOT / "data" / "mappings" / "ets2_countries.json"
LOCK_PATH = REPO_ROOT / "state" / "prices.lock.json"
ICONS_DIR = REPO_ROOT / "assets" / "icons"


def test_audit_and_validate_taint_pattern_labels_stay_in_sync() -> None:
    """Validate and audit maintain independent copies of the exact 8 D-16 taint markers."""
    audit_labels = [label for label, _ in AUDIT_TAINT_PATTERNS]
    validate_labels = [label for label, _ in VALIDATE_TAINT_PATTERNS]
    assert audit_labels == validate_labels
    assert audit_labels == [
        "CC BY-SA",
        "ODbL",
        "OpenStreetMap",
        "osm-legal-default-speeds",
        "GlobalPetrolPrices",
        "CC BY-NC-ND",
        "MyLPG",
        "IEA",
    ]


def test_committed_repo_data_and_lockfile_pass_license_taint_gate() -> None:
    """All 225 law files, curated baselines, mappings, and prices.lock.json have zero taint."""
    report = scan_repo_and_artifacts_for_taint(REPO_ROOT)
    assert isinstance(report, TaintScanReport)
    assert report.ok is True, report.violations
    assert report.violation_count == 0
    assert report.violations == []
    # 225 country law files + currencies.json + ets2_countries.json + country_aliases.json
    # + tier3_fuel_baselines.json + state/prices.lock.json (+ speed_audit_allowlist.json)
    assert report.files_scanned >= 230


def test_generated_snapshots_and_built_core_packages_pass_license_taint_gate(
    tmp_path: pathlib.Path,
) -> None:
    """Freshly generated 225-territory Summer/Winter snapshots and Core packages have zero taint."""
    snapshot_paths: list[pathlib.Path] = []
    for season in ("summer", "winter"):
        snapshot = load_or_build_snapshot(
            season,
            laws_dir=LAWS_DIR,
            mappings_path=MAPPINGS_PATH,
            baseline_dir=BASELINE_DIR,
            prices_lock_path=LOCK_PATH,
        )
        assert len(snapshot.countries) == 225
        snap_path = tmp_path / f"realism-snapshot-{season}.json"
        snap_path.write_bytes(serialize_snapshot_bytes(snapshot))
        snapshot_paths.append(snap_path)

    built = build_core_editions(
        tmp_path / "dist",
        laws_dir=LAWS_DIR,
        mappings_path=MAPPINGS_PATH,
        baseline_dir=BASELINE_DIR,
        icons_dir=ICONS_DIR,
        prices_lock_path=LOCK_PATH,
    )
    package_paths = [
        built["summer"].workshop_dir,
        built["summer"].local_zip_path,
        built["winter"].workshop_dir,
        built["winter"].local_zip_path,
    ]

    full_report = scan_repo_and_artifacts_for_taint(
        REPO_ROOT,
        snapshot_paths=snapshot_paths,
        package_paths=package_paths,
    )
    assert full_report.ok is True, full_report.violations
    assert full_report.violation_count == 0
    assert full_report.snapshots_scanned == 2
    assert full_report.packages_scanned == 4
    # 230 repo files + 2 snapshots + 4 packages (~577-578 text files each, excluding mod_icon.jpg)
    assert full_report.files_scanned >= 230 + 2 + 570 * 4

    for pkg_path in package_paths:
        pkg_report = scan_package_for_taint(pkg_path)
        assert pkg_report.ok is True, pkg_report.violations
        assert pkg_report.packages_scanned == 1
        assert pkg_report.files_scanned >= 500


@pytest.mark.parametrize(
    ("sample_text", "expected_marker"),
    [
        ("Licensed under CC BY-SA 2.0", "CC BY-SA"),
        ("Mirror tag cc-by-sa 4.0", "CC BY-SA"),
        ("Released under ODbL 1.0 terms", "ODbL"),
        ("Source: https://www.openstreetmap.org/wiki/Speed_limits", "OpenStreetMap"),
        ("Generated by osm-legal-default-speeds ruleset", "osm-legal-default-speeds"),
        ("Scraped from GlobalPetrolPrices.com", "GlobalPetrolPrices"),
        ("Licensed under CC BY-NC-ND 3.0", "CC BY-NC-ND"),
        ("Data courtesy of MyLPG.eu", "MyLPG"),
        ("Paid IEA monthly retail report", "IEA"),
        ("Published by the International Energy Agency", "IEA"),
    ],
)
def test_every_forbidden_taint_marker_is_detected_in_validator_and_audit(
    tmp_path: pathlib.Path,
    sample_text: str,
    expected_marker: str,
) -> None:
    """All 8 D-16 forbidden license/source markers fail both validate/ and audit/ scanners."""
    collector = ValidationCollector()
    check_license_taint_bytes(
        sample_text.encode("utf-8"),
        "universal/description.txt",
        collector,
    )
    val_report = collector.build_report("synthetic", "workshop")
    assert val_report.ok is False
    assert any(
        issue.code == "ETS2V2-INV-LICENSE-TAINT" and expected_marker in issue.detail
        for issue in val_report.issues
    )

    # Synthetic repo tree with tainted law JSON
    fake_repo = tmp_path / "repo"
    law_file = fake_repo / "data" / "laws" / "countries" / "xx.json"
    law_file.parent.mkdir(parents=True, exist_ok=True)
    law_file.write_text(f'{{"note": "{sample_text}"}}\n', encoding="utf-8")

    repo_report = scan_repo_and_artifacts_for_taint(fake_repo)
    assert repo_report.ok is False
    assert repo_report.violation_count >= 1
    assert any(
        isinstance(v, TaintViolation) and v.marker == expected_marker
        for v in repo_report.violations
    )

    # Synthetic .scs / .zip package with tainted .sui member
    tainted_zip = tmp_path / "tainted.scs"
    with zipfile.ZipFile(tainted_zip, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("def/country/test.sui", f"# {sample_text}\n")
    pkg_report = scan_package_for_taint(tainted_zip)
    assert pkg_report.ok is False
    assert any(v.marker == expected_marker for v in pkg_report.violations)


